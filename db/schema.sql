DROP TABLE IF EXISTS BENEFICIO_META;
DROP TABLE IF EXISTS BENEFICIO;

-- Tabela principal com dados fixos e essenciais
CREATE TABLE BENEFICIO (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOME VARCHAR(100) NOT NULL,
  VERSION BIGINT DEFAULT 0
);

-- Tabela de metadados para armazenar atributos dinâmicos
CREATE TABLE BENEFICIO_META (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BENEFICIO_ID BIGINT NOT NULL,
    METAKEY VARCHAR(50) NOT NULL,
    METAVALUE VARCHAR(255),
    CONSTRAINT fk_beneficio
        FOREIGN KEY(BENEFICIO_ID)
        REFERENCES BENEFICIO(ID)
        ON DELETE CASCADE,
    UNIQUE (BENEFICIO_ID, METAKEY)
);